"""
plan.py — ImplementationPlan and ImplementationApproval models.

These tables are owned by the AI service and store the lifecycle of
feature requests from initial generation through human approval.

Lifecycle:
    pending_investigation → awaiting_approval → approved / rejected / changes_requested

Owned by: AI Service.
"""

from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import (
    Boolean,
    DateTime,
    ForeignKey,
    Integer,
    String,
    Text,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base


class ImplementationPlan(Base):
    """
    Stores a feature implementation plan generated by the Feature Planner Graph.

    A plan has:
      - A structured task list (JSONB) with each task describing files to change,
        the kind of change, and acceptance criteria.
      - A lifecycle status managed by approval endpoints.
      - A version counter incremented each time changes are requested + re-planned.

    Status transitions:
        pending_investigation → awaiting_approval
        awaiting_approval     → approved | rejected | changes_requested
        changes_requested     → awaiting_approval  (after re-planning)
    """

    __tablename__ = "implementation_plans"

    id: Mapped[str] = mapped_column(
        UUID(as_uuid=False),
        primary_key=True,
        default=lambda: str(uuid.uuid4()),
    )

    # Tenant isolation
    organization_id: Mapped[int] = mapped_column(Integer, nullable=False, index=True)
    repository_id: Mapped[int] = mapped_column(Integer, nullable=False, index=True)
    created_by_user_id: Mapped[int] = mapped_column(Integer, nullable=False)

    # Link to the conversation that triggered planning
    conversation_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("conversations.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    # The original feature request text from the user
    feature_request: Mapped[str] = mapped_column(Text, nullable=False)

    # Structured plan: { title, summary, tasks: [...], affected_files: [...],
    #                    estimated_complexity, base_commit_sha }
    plan_data: Mapped[dict | None] = mapped_column(JSONB, nullable=True)

    # Investigation context gathered during planning (for debugging / transparency)
    investigation_context: Mapped[dict | None] = mapped_column(JSONB, nullable=True)

    # Status lifecycle
    status: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
        default="pending_investigation",
        index=True,
    )

    # Version counter — bumped on each changes_requested → re-plan cycle
    version: Mapped[int] = mapped_column(Integer, nullable=False, default=1)

    # Git ref at the time of planning
    base_commit_sha: Mapped[str | None] = mapped_column(String(40), nullable=True)

    # Error message if planning failed
    error_message: Mapped[str | None] = mapped_column(Text, nullable=True)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )

    # Relationships
    approvals: Mapped[list[ImplementationApproval]] = relationship(
        "ImplementationApproval",
        back_populates="plan",
        cascade="all, delete-orphan",
        order_by="ImplementationApproval.created_at",
    )


class ImplementationApproval(Base):
    """
    Immutable audit record of each approval action taken on a plan.

    Every approve / reject / request-changes creates a new row.
    The current effective action is the latest row for a plan_id.
    """

    __tablename__ = "implementation_approvals"

    id: Mapped[str] = mapped_column(
        UUID(as_uuid=False),
        primary_key=True,
        default=lambda: str(uuid.uuid4()),
    )

    plan_id: Mapped[str] = mapped_column(
        UUID(as_uuid=False),
        ForeignKey("implementation_plans.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    user_id: Mapped[int] = mapped_column(Integer, nullable=False)

    # approved | rejected | changes_requested
    action: Mapped[str] = mapped_column(String(30), nullable=False)

    # Git SHA at the time of approval — for traceability
    commit_sha_at_approval: Mapped[str | None] = mapped_column(String(40), nullable=True)

    # Reviewer comment or change-request feedback
    comment: Mapped[str | None] = mapped_column(Text, nullable=True)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )

    # Relationships
    plan: Mapped[ImplementationPlan] = relationship(
        "ImplementationPlan", back_populates="approvals"
    )
